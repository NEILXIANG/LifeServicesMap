#!/usr/bin/env python3
"""Regenerate cities/_fixture/ ("Testville") from a slice of the Kamloops data.

The fixture exists to prove the engine is city-agnostic: tests/engine/ builds it
and runs the page. It is deliberately small (fast) and deliberately *not*
Kamloops by name, storage prefix, landmarks or guide text, so anything still
hard-wired to Kamloops in the engine shows up here first.

    python3 tests/make-fixture-city.py      # rewrites cities/_fixture/
"""
import json, os, re, shutil, sys

_r = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(_r))
import kamdata

SRC = kamdata.city_dir('kamloops')
DST = os.path.join(kamdata.ROOT, 'cities', '_fixture')
LANGS = ['zh', 'en', 'fr', 'es', 'ko', 'ja']

def main():
    if os.path.exists(DST):
        shutil.rmtree(DST)
    os.makedirs(os.path.join(DST, 'guide'))

    meta = kamdata.city_meta('kamloops')
    meta.pop('deploy', None)   # never deployable: deploy.sh refuses a city without this
    meta.update({
        '_comment': 'Test city for engine tests. Generated by tests/make-fixture-city.py — do not edit by hand.',
        'id': '_fixture', 'title': 'Testville Life Guide',
        'description': 'Test city for the engine tests.',
        'siteUrl': 'https://example.invalid/', 'storagePrefix': 'testville',
        'searchStopwords': ['testville', 'bc'], 'validate': {'minPlaces': 1},
    })
    json.dump(meta, open(os.path.join(DST, 'city.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=2)

    kamdata.use('kamloops')
    P = kamdata.load('P'); T = kamdata.load('TASKS'); BR = kamdata.load('BR')
    # every place a task card points at, then the first place of each category
    keep = {t['place'] for t in T if t.get('place')}
    # the urgent care centre(s) the health answer points to (CITY.upcc), so that path is exercised
    src_js = open(os.path.join(SRC, 'data.js'), encoding='utf-8').read()
    upcc = re.findall(r"'([0-9a-f]{8})'", re.search(r"upcc:\[([^\]]*)\]", src_js).group(1))
    keep |= set(upcc)
    seen = set()
    for p in P:
        if p['c'] not in seen:
            keep.add(p['id']); seen.add(p['c'])
    places = [p for p in P if p['id'] in keep]
    ids = {p['id'] for p in places}
    for p in places:
        if 'sameComplex' in p:
            p['sameComplex'] = [i for i in p['sameComplex'] if i in ids]
            if not p['sameComplex']:
                del p['sameComplex']
    first_route = next(iter(BR))
    def dump(name, value):
        json.dump(value, open(os.path.join(DST, name), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    dump('places.json', places)
    dump('tasks.json', T)
    dump('bus-routes.json', {first_route: BR[first_route]})
    dump('quarantine.json', [])
    dump('landmarks.json', [])
    shutil.copy(os.path.join(SRC, 'regions.json'), os.path.join(DST, 'regions.json'))

    for lang in LANGS:
        open(os.path.join(DST, 'guide', lang + '.html'), 'w', encoding='utf-8').write(
            '\n<h3>{CITY}</h3>\n<p>Fixture guide text (%s).</p>\n' % lang)

    d = open(os.path.join(SRC, 'data.js'), encoding='utf-8').read()
    d = re.sub(r"name:\{zh:'Kamloops',en:'Kamloops',fr:'Kamloops',es:'Kamloops',ko:'Kamloops',ja:'Kamloops'\}",
               "name:{zh:'Testville',en:'Testville',fr:'Testville',es:'Testville',ko:'Testville',ja:'Testville'}", d)
    d = d.replace("key:'kamloops'", "key:'testville'").replace("navSuffix:', Kamloops, BC'", "navSuffix:', Testville, BC'")
    d = re.sub(r'const FAV_MIGRATE=\{.*?\};', 'const FAV_MIGRATE={};', d, flags=re.S)
    d = re.sub(r'const LANDMARK_GLOSS=\{.*?\n\};', 'const LANDMARK_GLOSS={};', d, flags=re.S)
    # one route here, so the coverage note says so (validate.py checks the count)
    d = re.sub(r"UI\.(zh|en|fr|es|ko|ja)\.busCoverage='(?:[^'\\]|\\.)*';",
               lambda m: "UI.%s.busCoverage='{CITY}: 1 route ({TRANSIT}).';" % m.group(1), d)
    # 2026-10-04: Kamloops' own texts (data note, third-party sentence, legal help, urgent care line) are
    # dropped so Testville shows the engine's generic defaults — the proof that those defaults read
    # correctly in a city that sets nothing. Fares and the police line are required, so they get
    # obviously fictional values (555-01xx is reserved for fiction).
    d = re.sub(r"UI\.(zh|en|fr|es|ko|ja)\.(noteCoverage|noteThirdParty|legalLocal|hcUpcc)='(?:[^'\\]|\\.)*';\n", '', d)
    d = re.sub(r"UI\.(zh|en|fr|es|ko|ja)\.busFareText='(?:[^'\\]|\\.)*';",
               lambda m: "UI.%s.busFareText='{CITY} fare text ({TRANSIT}).';" % m.group(1), d)
    d = re.sub(r"police:'[^']*'", "police:'250-555-0100'", d)
    d = '// Generated by tests/make-fixture-city.py from cities/kamloops/data.js — do not edit by hand.\n' + d
    assert "name:{zh:'Testville'" in d and 'FAV_MIGRATE={};' in d and 'LANDMARK_GLOSS={};' in d
    assert 'legalLocal' not in d and "police:'250-555-0100'" in d and '{CITY} fare text' in d
    open(os.path.join(DST, 'data.js'), 'w', encoding='utf-8').write(d)
    print('cities/_fixture: %d places, %d tasks, 1 bus route' % (len(places), len(T)))

if __name__ == '__main__':
    main()
